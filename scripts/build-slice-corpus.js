#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');

function stripMarkdown(value) {
  return String(value || '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*_>#]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function parseIndex(markdown, indexPath) {
  const dateMatch = String(indexPath).match(/(\d{4}-\d{2}-\d{2})\/index\.md$/);
  const date = dateMatch ? dateMatch[1] : null;
  const dir = path.posix.dirname(indexPath);
  const parts = String(markdown || '').split(/^###\s+/m).slice(1);
  return parts.map((chunk) => {
    const firstBreak = chunk.indexOf('\n');
    const heading = (firstBreak >= 0 ? chunk.slice(0, firstBreak) : chunk).trim();
    const body = firstBreak >= 0 ? chunk.slice(firstBreak + 1).trim() : '';
    const link = heading.match(/^\[([^\]]+)\]\(([^)]+)\)/);
    if (!link || !link[2].endsWith('.md')) return null;
    const title = stripMarkdown(link[1]);
    const href = link[2];
    const fullPath = path.posix.normalize(path.posix.join(dir, href));
    const paragraphs = body.split(/\n\s*\n/).map(stripMarkdown).filter(Boolean);
    const summary = paragraphs.find((p) => !/^Companion visual:/i.test(p) && !/^Interactive visual artifact/i.test(p)) || '';
    const carryMatch = body.match(/(?:(?:the )?line worth carrying is|candidate (?:rule|principle|test) is|pocket version is shorter):?\s*\*\*([^*]+)\*\*/i);
    const carry = carryMatch ? stripMarkdown(carryMatch[1]) : '';
    const slug = path.posix.basename(href, '.md');
    return {
      id: `${date || 'undated'}:${slug}`,
      date,
      title,
      path: fullPath,
      summary,
      carry,
      text: stripMarkdown(body)
    };
  }).filter(Boolean);
}

function walkIndexes(root) {
  const sliceRoot = path.join(root, 'slices');
  const found = [];
  if (!fs.existsSync(sliceRoot)) return found;
  const stack = [sliceRoot];
  while (stack.length) {
    const current = stack.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes:true })) {
      const next = path.join(current, entry.name);
      if (entry.isDirectory()) stack.push(next);
      else if (entry.isFile() && entry.name === 'index.md') found.push(next);
    }
  }
  return found.sort();
}

function build(root) {
  const rows = walkIndexes(root).flatMap((file) => {
    const rel = path.relative(root, file).split(path.sep).join('/');
    return parseIndex(fs.readFileSync(file, 'utf8'), rel);
  });
  const outDir = path.join(root, 'generated');
  fs.mkdirSync(outDir, { recursive:true });
  const target = path.join(outDir, 'slice-corpus.js');
  const payload = `/* generated by scripts/build-slice-corpus.js; do not hand-edit */\nwindow.DAILY_SLICE = ${JSON.stringify(rows, null, 2)};\n`;
  fs.writeFileSync(target, payload);
  return { target, count:rows.length };
}

if (require.main === module) {
  const root = path.resolve(process.argv[2] || path.join(__dirname, '..'));
  const result = build(root);
  process.stdout.write(`wrote ${result.count} slice records to ${result.target}\n`);
}

module.exports = { parseIndex, build };
